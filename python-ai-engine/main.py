import os
import json
import asyncio
from contextlib import asynccontextmanager
from typing import Optional, List, Dict, Any
from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field
from rag_service import RAGService

# Initialize RAG service singleton
rag_service = RAGService()


@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Function:
        Manages the application lifecycle, executing startup health checks against
        local Ollama daemons and ChromaDB persistence, followed by graceful resource release.

    Input:
        app (FastAPI): The root FastAPI application instance.

    Output:
        None: Yields control to the application during runtime.
    """
    # Startup validation
    try:
        count = rag_service.collection.count()
        print(f"[AI Engine Startup] ChromaDB connected. Total active chunks: {count}")
        models = rag_service.ollama_client.list()
        print(f"[AI Engine Startup] Ollama connected. Available models verified.")
    except Exception as e:
        print(f"[AI Engine Startup Warning] Component check warning: {e}")
    yield
    print("[AI Engine Shutdown] Service gracefully shutting down.")


app = FastAPI(
    title="Enterprise Local RAG Chatbot - AI Engine",
    description="Air-gapped vector search and LLM inference engine using ChromaDB and Ollama.",
    version="2.0.0",
    lifespan=lifespan
)

# Cross-Origin Resource Sharing for internal microservices
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class DocumentIngestPayload(BaseModel):
    fileName: Optional[str] = Field(None, description="Human-readable filename of the SOP document")
    absolutePath: str = Field(..., description="Absolute filesystem path to the target PDF file")
    fileSizeKb: Optional[int] = Field(0, description="File size measured in kilobytes")
    lastModified: Optional[str] = Field(None, description="ISO-8601 timestamp of last file modification")


class ChatRequest(BaseModel):
    query: str = Field(..., min_length=1, description="The operational SOP inquiry submitted by the employee")
    top_k: Optional[int] = Field(4, ge=1, le=10, description="Maximum number of context chunks to retrieve")


class Citation(BaseModel):
    document: str = Field(..., description="Source SOP document name")
    page: int = Field(..., description="1-indexed document page number")
    section: str = Field(..., description="Extracted section heading or operational context")
    snippet: str = Field(..., description="Extracted text chunk excerpt")
    distance: float = Field(..., description="Cosine distance metric from query vector")


class ChatResponse(BaseModel):
    answer: str = Field(..., description="Grounded response generated by local LLM")
    citations: List[Citation] = Field(default_factory=list, description="List of source citations")
    context_count: int = Field(..., description="Number of context segments incorporated into prompt")


