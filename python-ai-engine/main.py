@app.get("/api/health", tags=["System"])
async def health_check() -> Dict[str, Any]:
    """
    Function:
        Executes real-time diagnostics on ChromaDB persistence and Ollama daemon responsiveness.
        Provides telemetry metrics utilized by the Java Orchestrator and Streamlit UI.

    Input:
        None: Handled via standard HTTP GET.

    Output:
        Dict[str, Any]: Health diagnostic metrics containing ChromaDB chunk count
                        and Ollama daemon reachability status.
    """
    try:
        chunk_count = rag_service.collection.count()
        ollama_status = "healthy"
        try:
            rag_service.ollama_client.list()
        except Exception:
            ollama_status = "unreachable"

        return {
            "status": "healthy" if ollama_status == "healthy" else "degraded",
            "chroma_total_chunks": chunk_count,
            "ollama_status": ollama_status
        }
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Health probe failure: {str(e)}"
        )


@app.post("/api/documents/ingest", tags=["Ingestion"])
async def ingest_document(payload: DocumentIngestPayload) -> Dict[str, Any]:
    """
    Function:
        Asynchronously delegates PDF text extraction, semantic chunking, embedding generation,
        and ChromaDB storage to a background worker thread. Guarantees non-blocking execution
        for the orchestrator while processing heavy multi-page documents.

    Input:
        payload (DocumentIngestPayload): JSON payload specifying absolute file path and metadata.

    Output:
        Dict[str, Any]: Operational receipt confirming total pages and indexed chunk count.
                        Raises HTTP 404 if file does not exist, or HTTP 500 on parser error.
    """
    if not os.path.exists(payload.absolutePath):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Requested document not found on host filesystem: {payload.absolutePath}"
        )

    try:
        # Offload synchronous PDF vectorization to thread pool to preserve event loop latency
        result = await asyncio.to_thread(
            rag_service.ingest_pdf,
            file_path=payload.absolutePath,
            file_name=payload.fileName
        )
        return result
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Ingestion pipeline failure: {str(e)}"
        )


@app.post("/api/chat", response_model=ChatResponse, tags=["Inference"])
async def chat(request: ChatRequest) -> ChatResponse:
    """
    Function:
        Asynchronously handles employee natural-language inquiries by coordinating vector
        retrieval, relevance filtering, and local Llama 3.1 inference within a worker thread.
        Enforces strict hallucination guardrails.

    Input:
        request (ChatRequest): Incoming query payload containing user prompt and top_k parameter.

    Output:
        ChatResponse: Structured Pydantic response containing the verified answer,
                      individual citation objects, and context metrics.
    """
    cleaned_query = request.query.strip()
    if not cleaned_query:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Query string cannot be blank."
        )

    try:
        # Execute query retrieval and Ollama inference asynchronously
        result = await asyncio.to_thread(
            rag_service.query,
            user_query=cleaned_query,
            top_k=request.top_k or 4
        )
        return ChatResponse(**result)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"RAG query execution error: {str(e)}"
        )


@app.post("/api/chat/stream", tags=["Inference"])
async def chat_stream(request: ChatRequest):
    """
    Function:
        Streams token generation events in real-time using ndjson format.
        Yields citation headers, real-time token chunks, and final completion payload.

    Input:
        request (ChatRequest): Query string and top_k parameters.

    Output:
        StreamingResponse: application/x-ndjson stream of JSON objects.
    """
    cleaned_query = request.query.strip()
    if not cleaned_query:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Query string cannot be blank."
        )

    def event_stream():
        for event in rag_service.query_stream(user_query=cleaned_query, top_k=request.top_k or 4):
            yield json.dumps(event) + "\n"

    return StreamingResponse(
        event_stream(),
        media_type="application/x-ndjson"
    )


